export const networkIdentitySource = 'https://raw.githubusercontent.com/tempoxyz/tempo/main'

export function parseNetworkIdentity(value: unknown) {
  if (!value || typeof value !== 'object') throw new Error('Invalid network identity')
  const { from_epoch, identity } = value as Record<string, unknown>
  if (
    typeof from_epoch !== 'number' ||
    !Number.isSafeInteger(from_epoch) ||
    from_epoch < 0 ||
    typeof identity !== 'string' ||
    !/^0x[0-9a-fA-F]{192}$/.test(identity)
  )
    throw new Error('Invalid network identity')
  return { fromEpoch: from_epoch, identity }
}

export type NetworkIdentities = {
  mainnet: ReturnType<typeof parseNetworkIdentity>
  testnet: ReturnType<typeof parseNetworkIdentity>
}

export function renderNetworkIdentitySnippets(identities: NetworkIdentities) {
  const regions = Object.entries(identities).map(([network, { fromEpoch, identity }]) => {
    const chain = network === 'testnet' ? ' --chain testnet' : ''
    return `// [!region ${network}-identity]
${identity}
// [!endregion ${network}-identity]

// [!region ${network}-override]
tempo node${chain} \\
  --consensus.network-identity ${identity} \\
  --consensus.network-identity-from-epoch ${fromEpoch}
// [!endregion ${network}-override]`
  })
  return `// Generated by pnpm sync:network-identities. Do not edit.
// Source: ${networkIdentitySource}/{mainnet,testnet}-network-identity.json

${regions.join('\n\n')}\n`
}
